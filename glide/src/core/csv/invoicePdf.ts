import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';
import { formatCents } from '../../shared/format';
import type { InvoiceLine } from './exporter';

/** Member spending statement as a simple, printable PDF. */
export async function invoicePdf(brand: string, member: { discord_id: string | null; username: string; display_name: string | null }, lines: InvoiceLine[], totals: Record<string, number>, range: string): Promise<Buffer> {
  const doc = await PDFDocument.create();
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const ascii = (s: string) => s.normalize('NFKD').replace(/[^\x20-\x7e]/g, '');
  let page = doc.addPage([612, 792]);
  let y = 740;
  const text = (s: string, x: number, size = 10, f = font, color = rgb(0.1, 0.1, 0.15)) => page.drawText(ascii(s), { x, y, size, font: f, color });
  text(`${brand} - Spending Statement`, 48, 18, bold);
  y -= 22;
  text(`Member: ${member.display_name ?? member.username}   Discord ID: ${member.discord_id ?? '-'}   Period: ${range}`, 48, 10);
  y -= 28;
  const header = () => {
    for (const [label, x] of [['Date', 48], ['Retailer', 112], ['Order', 200], ['Item', 300], ['Qty', 470], ['Unit', 500], ['Total', 548]] as const) text(label, x, 9, bold);
    y -= 6;
    page.drawLine({ start: { x: 48, y }, end: { x: 564, y }, thickness: 0.5, color: rgb(0.6, 0.6, 0.7) });
    y -= 14;
  };
  header();
  for (const l of lines) {
    if (y < 72) {
      page = doc.addPage([612, 792]);
      y = 740;
      header();
    }
    text(l.placedAt.slice(0, 10), 48, 8);
    text(l.retailer.slice(0, 16), 112, 8);
    text(l.orderNumber.slice(0, 18), 200, 8);
    text(l.title.replace(/^Pok[ée]mon TCG:\s*/i, '').slice(0, 34), 300, 8);
    text(String(l.quantity), 470, 8);
    text(formatCents(l.unitCents, l.currency), 500, 8);
    text(formatCents(l.lineCents, l.currency), 548, 8);
    y -= 13;
  }
  y -= 10;
  for (const [cur, c] of Object.entries(totals)) {
    text(`Total (${cur}, pre-tax item value): ${formatCents(c, cur)}`, 360, 11, bold);
    y -= 16;
  }
  text('Generated by GLIDE from recorded orders. Canceled items excluded.', 48, 8, font, rgb(0.4, 0.4, 0.5));
  return Buffer.from(await doc.save());
}
